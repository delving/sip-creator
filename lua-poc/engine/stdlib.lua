-- gs(parts, slot_texts) — builds a template-string value for
-- builder.lua's content/attribute resolution. `parts` is the array of
-- literal fragments (#parts == #slot_texts + 1, as usual for an
-- interpolated string split around its slots). `slot_texts` is the
-- ALREADY-STRINGIFIED text of each interpolated slot, in Groovy's own
-- interpolation rules (spec 4.6: a node renders its text, a list renders
-- "[a, b]", and — this is the caller's responsibility, not gs's — a nil
-- value must be pre-rendered as the literal word "null", never passed as
-- a real Lua nil, so that the slot_texts array can never contain a hole).
-- Task 8's codegen is expected to build slot_texts via
-- `stdlib.to_text(v) or "null"` per slot.
--
-- Returns { __gstring = true, text = <rendered>, suppressed = <bool> }.
-- Per spec 3.4: suppressed is true only when there is at least one slot
-- AND every slot's trimmed text is empty. A zero-slot template (a plain
-- literal with no interpolation) is never suppressed.
function M.gs(parts, slot_texts)
  slot_texts = slot_texts or {}
  local rendered = {}
  for i = 1, #parts do
    rendered[#rendered + 1] = parts[i]
    local t = slot_texts[i]
    if t ~= nil then
      rendered[#rendered + 1] = t
    end
  end

  local suppressed = #slot_texts > 0
  for _, t in ipairs(slot_texts) do
    if M.trim(t) ~= "" then
      suppressed = false
      break
    end
  end

  return { __gstring = true, text = table.concat(rendered), suppressed = suppressed }
end

return M
