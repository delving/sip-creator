--[==[
stdlib.lua — pure-Lua T1 stdlib (Task 7 of the Lua mapping-engine
feasibility project). Ports the T1-relevant subset of `MappingCategory`
(docs/specs/mapping-language-core.md section 4.1), `GroovyNode`'s own
convenience methods (section 4.2) and plain String/Groovy-GDK methods
(section 4.3) that Task 2's corpus scan found in the T1 tier.

Surface: every function takes a string, a Task-6 node
(engine/node.lua), or a Task-6 absorber as its first ("receiver")
argument. It is coerced via `to_text`: a string passes through, a
node/absorber is reduced via its own `:text()` (an absorber's `:text()` is
"", per node.lua), and a plain Lua array (standing in for a Groovy
`List`/`NodeList`) renders as `"[a, b]"` (spec section 1 / 4.3).

DELIBERATE DEVIATION from spec section 5.2's per-function null table —
documented here and in task-7-report.md, not hidden:

  A nil or absorber *receiver* (first argument) is null-safe: it coerces to
  "" and the function proceeds as if called on the empty string, rather
  than reproducing Groovy's NPE-at-call-site. This is what the brief's own
  worked example specifies (`assert.equal("", stdlib.capitalize(nil))`,
  task-7-brief.md step 1) and it keeps the engine total — a mapping.lua
  script generated by Task 8 must be able to call these functions on the
  result of a Task-6 navigation miss without crashing, exactly as Task 6's
  absorber was built to make chained navigation total. Reproducing every
  NPE from section 5.2 would reintroduce the crash-on-absence behaviour
  Task 6 deliberately engineered away.

  A nil *later* argument (a regex/delimiter/needle/replacement — a
  code-level literal from generated mapping source, not absent input data)
  is NOT absorbed: it raises a Lua error. This preserves the spirit of
  section 5.2's "null later arg" rows (also NPE in Groovy) for what is
  actually a programmer/codegen bug rather than a data-absence case.

  `sanitizeURN` keeps its explicit null-safe "" behaviour (spec 4.1 #23) —
  here that coincides with the general receiver rule, so there is no
  special case to write.

  `asBoolean` was already null-safe in Groovy ("not dispatched — null is
  falsy", spec 5.2), so no deviation there either.

Explicitly OUT OF SCOPE for this task (documented in task-7-report.md, not
silently dropped):
  - `getAt` (spec 4.1 #8): throws unconditionally in the reference impl and
    is superseded by the `node['x']` open question (spec 2.4); not needed
    by any T1 builder script.
  - `plus`/`or` (spec 4.1 #12/#13) and `multiply` with a delimiter
    (#15/#16): operate on `List<GroovyNode>` via `flatten`/`getValueNodes`,
    infrastructure Task 6 did not expose (only `get`/`get_`, not a
    recursive multi-match collector or a live "*" children view). Not in
    Task 2's top-20 T1 constructs.
  - `multiply`/`power`/`rightShift` with a closure (#14/#17/#18): the spec
    itself marks these "[spike: out of scope, sub-project 2]" (section
    4.4) — closures are a T2 construct.
  - `calculateAge`/`calculateAgeRange` (spec 4.7): standard mapping
    functions loaded from a resource file at runtime, not part of the
    MappingCategory/GroovyNode/String stdlib this task ports.
  - `lookupX`/dictionary lookups (spec 7.3): Facts & lookups machinery,
    generated per-mapping, not a fixed stdlib function.
