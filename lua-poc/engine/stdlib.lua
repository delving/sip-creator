-- #9 indexOf(node, s) / plain String indexOf(s) — LITERAL substring search
-- (Java's String.indexOf is not a regex method), 0-based, -1 when absent.
function M.indexOf(v, needle)
  local str = receiver_text(v)
  require_arg(needle, "indexOf", "needle")
  local fs = str:find(needle, 1, true)
  if not fs then
    return -1
  end
  return fs - 1
end

-- #10/#11 substring(node, from[, to]) — Java 0-based, exclusive-end
-- semantics; out-of-range raises (StringIndexOutOfBoundsException
-- equivalent).
function M.substring(v, from, to)
  local str = receiver_text(v)
  local len = #str
  if to == nil then
    if from < 0 or from > len then
      error("substring: index " .. tostring(from) .. " out of range for length " .. len, 2)
    end
    return str:sub(from + 1)
  end
  if from < 0 or to > len or from > to then
    error("substring: range [" .. from .. "," .. to .. ") out of bounds for length " .. len, 2)
  end
  return str:sub(from + 1, to)
end

-- replace(a, b) — LITERAL (non-regex) replacement, distinct from
-- replaceAll.
function M.replace(v, a, b)
  local str = receiver_text(v)
  require_arg(a, "replace", "target")
  require_arg(b, "replace", "replacement")
  if a == "" then
    return str
  end
  local parts = {}
  local pos = 1
  local alen = #a
  while true do
    local s = str:find(a, pos, true)
    if not s then
      parts[#parts + 1] = str:sub(pos)
      break
    end
    parts[#parts + 1] = str:sub(pos, s - 1)
    parts[#parts + 1] = b
    pos = s + alen
  end
  return table.concat(parts)
end

-- capitalize() — Groovy GDK: upper-cases the first character only.
function M.capitalize(v)
  local str = receiver_text(v)
  if str == "" then
    return ""
  end
  return str:sub(1, 1):upper() .. str:sub(2)
end

-- trim() — strips ASCII whitespace from both ends. (Simplification: Java's
-- trim() strips any char <= U+0020, Lua's %s is the practical ASCII
-- whitespace subset; not observed to diverge on the T1 corpus.)
function M.trim(v)
  local str = receiver_text(v)
  return (str:gsub("^%s+", ""):gsub("%s+$", ""))
end

-- toLowerCase() / toUpperCase() — Lua's string.lower/upper is byte-based
-- (ASCII); this is the "pin to root locale" behaviour spec 4.3
-- recommends, not the JVM's default-locale mapping.
function M.toLowerCase(v)
  return receiver_text(v):lower()
end

function M.toUpperCase(v)
  return receiver_text(v):upper()
end

-- toString() — identity for a string; a node's text; "[a, b]" for a plain
-- list (spec section 1/2.6).
function M.toString(v)
  return receiver_text(v)
end

-- toInteger() — Groovy GDK Integer.valueOf after trim; throws on junk
-- (including "", which is what a nil receiver coerces to and Groovy's own
-- "".toInteger() also throws on — no special-casing needed here).
function M.toInteger(v)
  local trimmed = M.trim(v)
  if trimmed:match("^[+-]?%d+$") then
    return math.floor(tonumber(trimmed))
  end
  error("toInteger: NumberFormatException for input string: \"" .. trimmed .. "\"", 2)
end

-- contains(s) / startsWith(s) / endsWith(s)
function M.contains(v, needle)
  local str = receiver_text(v)
  require_arg(needle, "contains", "needle")
  return str:find(needle, 1, true) ~= nil
end

function M.startsWith(v, prefix)
  local str = receiver_text(v)
  require_arg(prefix, "startsWith", "prefix")
  return str:sub(1, #prefix) == prefix
end

function M.endsWith(v, suffix)
  local str = receiver_text(v)
  require_arg(suffix, "endsWith", "suffix")
  if #suffix == 0 then
    return true
  end
  return str:sub(-#suffix) == suffix
end

-- isEmpty() — length zero; does NOT trim.
function M.isEmpty(v)
  return #receiver_text(v) == 0
end

-- size() — on a String/node, character/text length; on a plain list,
-- element count (spec 4.2/4.3: node.size() is a documented trap — it is
-- NOT a child count).
function M.size(v)
  if is_plain_list(v) then
    return #v
  end
  return #receiver_text(v)
end

-- join(sep) — Groovy GDK on a collection; stringifies each element. A nil
-- list is a programmer error (nothing to join), not absent data.
function M.join(list, sep)
  require_arg(list, "join", "list")
  local parts = {}
  for i, item in ipairs(list) do
    local t = to_text(item)
    parts[i] = t == nil and "null" or t
  end
  return table.concat(parts, sep or "")
end

