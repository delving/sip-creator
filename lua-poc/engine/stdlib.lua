local M = {}

-- Coerces a stdlib argument: string passes through; a node/absorber (any
-- table exposing :text()) reduces to its text; a plain Lua array (no
-- :text method — standing in for a Groovy List/NodeList) renders
-- "[elem, elem]" recursively (spec section 1: NodeList.toString() is
-- ArrayList's `[a, b]`); nil stays nil (the one case callers must
-- distinguish, per the module header's null-safety design).
local function to_text(v)
  if v == nil then
    return nil
  end
  local t = type(v)
  if t == "string" then
    return v
  end
  if t == "table" then
    if v.text then
      return v:text()
    end
    local parts = {}
    for i, item in ipairs(v) do
      parts[i] = to_text(item)
      if parts[i] == nil then
        parts[i] = "null"
      end
    end
    return "[" .. table.concat(parts, ", ") .. "]"
  end
  return tostring(v)
end
M.to_text = to_text

-- Null-safe coercion for a receiver argument: nil/absorber -> "" (see
-- module header for why this diverges from spec 5.2's NPE rows).
local function receiver_text(v)
  local s = to_text(v)
  if s == nil then
    return ""
  end
  return s
end

-- A later (code-level) argument must not be nil; nil here is a programmer
-- error, not absent data (see module header).
local function require_arg(v, fname, argname)
  if v == nil then
    error(fname .. ": nil " .. argname .. " (not a data-absence case — a literal argument was expected)", 3)
  end
  return v
end

