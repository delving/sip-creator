-- #1 replaceAll(s, regex, replacement) — Lua pattern, not java.util.regex;
-- translation from Groovy regex to a Lua pattern is the converter's job
-- (Task 8), per spec section 9.4.
function M.replaceAll(s, pattern, repl)
  local str = receiver_text(s)
  require_arg(pattern, "replaceAll", "pattern")
  require_arg(repl, "replaceAll", "replacement")
  return (str:gsub(pattern, repl))
end

local function raw_split(str, pattern)
  if str == "" then
    return { "" }
  end
  local parts = {}
  local pos = 1
  local len = #str
  while true do
    local s, e = str:find(pattern, pos)
    if not s then
      parts[#parts + 1] = str:sub(pos)
      break
    end
    if e < s then
      -- zero-width match: consume one character to avoid looping forever
      parts[#parts + 1] = str:sub(pos, s)
      pos = s + 1
    else
      parts[#parts + 1] = str:sub(pos, s - 1)
      pos = e + 1
    end
    if pos > len + 1 then
      parts[#parts + 1] = ""
      break
    end
  end
  return parts
end

-- #2/#3 split(s, regex[, limit]) — JDK trailing-empty-removal semantics
-- when no limit (or limit == 0) is given; an explicit positive limit caps
-- the result count, with the final element holding the unsplit remainder.
-- Simplification: a negative limit is treated the same as "no limit"
-- (JDK's negative-limit "no trailing removal" nuance is not reproduced —
-- not observed in the T1 corpus, see task-7-report.md).
function M.split(s, pattern, limit)
  local str = receiver_text(s)
  require_arg(pattern, "split", "pattern")

  if limit and limit > 0 then
    local parts = {}
    local pos = 1
    local len = #str
    while #parts < limit - 1 do
      local fs, fe = str:find(pattern, pos)
      if not fs then
        break
      end
      if fe < fs then
        parts[#parts + 1] = str:sub(pos, fs)
        pos = fs + 1
      else
        parts[#parts + 1] = str:sub(pos, fs - 1)
        pos = fe + 1
      end
      if pos > len + 1 then
        break
      end
    end
    parts[#parts + 1] = str:sub(pos)
    return parts
  end

  local parts = raw_split(str, pattern)
  if #parts > 1 then
    while #parts > 0 and parts[#parts] == "" do
      table.remove(parts)
    end
  end
  return parts
end

-- #4 matches(s, regex) — whole-string match.
function M.matches(s, pattern)
  local str = receiver_text(s)
  require_arg(pattern, "matches", "pattern")
  local fs, fe = str:find(pattern)
  return fs == 1 and fe == #str
end

-- #7 asBoolean(list) — list truth: empty -> false; a single element that is
-- itself a plain (non-node) list -> that list's truth; otherwise true.
-- nil is falsy without error (Groovy never dispatches on a null receiver).
local function is_plain_list(v)
  return type(v) == "table" and v.text == nil and v.__gstring == nil
end

function M.asBoolean(list)
  if list == nil then
    return false
  end
  if not is_plain_list(list) then
    return true
  end
  local n = #list
  if n == 0 then
    return false
  end
  if n == 1 and is_plain_list(list[1]) then
    return M.asBoolean(list[1])
  end
  return true
end

-- #19/#20/#21 sanitize(node/list/text) — the three Groovy overloads unify
-- here through `to_text`'s coercion (node -> text, list -> "[a, b]", text
-- -> itself). Collapses newlines to spaces then runs of spaces to one;
-- does NOT trim and does NOT strip apostrophes.
function M.sanitize(v)
  local s = receiver_text(v)
  s = s:gsub("[\r\n]+", " ")
  s = s:gsub(" +", " ")
  return s
end

-- #22 sanitizeURI(object) — percent-encodes ONLY space -> %20, [ -> %5B,
-- ] -> %5D, \ -> %5C; nothing else is touched. NOT a general
-- percent-encoder.
function M.sanitizeURI(v)
  local s = receiver_text(v)
  s = s:gsub(" ", "%%20")
  s = s:gsub("%[", "%%5B")
  s = s:gsub("%]", "%%5D")
  s = s:gsub("\\", "%%5C")
  return s
end

-- #23 sanitizeURN(object) — the one function that is null-safe by an
-- explicit guard in the reference implementation too: replaces each of
-- `: / _ space [ ] \` with '-' and collapses runs of '-'.
function M.sanitizeURN(v)
  local s = receiver_text(v)
  s = s:gsub("[:/_%[%]\\ ]", "-")
  s = s:gsub("%-+", "-")
  return s
end

